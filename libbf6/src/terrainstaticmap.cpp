bool static_layer_descriptors(const std::string& level, int layer,
                              int& cv, int& nh, int& third)
{
    const std::string lv = lower_of(level);
    for (const Row& r : kRows)
    {
        if (r.layer != layer) continue;
        if (lv != r.level) continue;
        cv = r.cv; nh = r.nh; third = r.third;
        return true;
    }
    return false;
}

bool static_layer_map_has(const std::string& level)
{
    const std::string lv = lower_of(level);
    for (const Row& r : kRows)
        if (lv == r.level) return true;
    return false;
}

